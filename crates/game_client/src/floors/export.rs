//! Exports the gameplay geometry of every zone (anchors, blockers, exit triggers, arrival
//! points) to `content/zone_geometry.ron` for the co-op server, which must not depend on Bevy.
//! The test fails when the file is stale; `TLD_WRITE_ZONES=1 cargo test -p game_client
//! zone_geometry` regenerates it.

use super::layout::{FloorLayout, elevator_exit_trigger};
use super::zones::{ZONE_IDS, build_zone, door_trigger};
use crate::collision::nearest_free;
use bevy::prelude::*;
use combat_core::{Aabb, Vec3 as CVec3};
use std::fmt::Write as _;

const PATH: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../content/zone_geometry.ron"
);

fn v3(out: &mut String, v: CVec3) {
    let _ = write!(out, "({:?}, {:?}, {:?})", v.x, v.y, v.z);
}

fn bv3(out: &mut String, v: Vec3) {
    v3(out, CVec3::new(v.x, v.y, v.z));
}

fn aabb(out: &mut String, b: &Aabb) {
    v3(out, b.min);
    out.push_str(", ");
    v3(out, b.max);
}

/// Must match `game::arrival`: in front of the door back to `from`, clear of its trigger.
fn arrival(layout: &FloorLayout, door: Vec3, yaw: f32) -> Vec3 {
    let facing = Quat::from_rotation_y(yaw) * Vec3::NEG_Z;
    nearest_free(door + facing * 2.6, door, &layout.blockers)
}

fn zone(out: &mut String, l: &FloorLayout) {
    let _ = writeln!(out, "    (\n        id: {:?},\n        anchors: [", l.zone);
    for (name, pos, yaw) in &l.anchors {
        let _ = write!(out, "            ({name:?}, ");
        bv3(out, *pos);
        let _ = writeln!(out, ", {yaw:?}),");
    }
    out.push_str("        ],\n        blockers: [\n");
    for b in &l.blockers {
        out.push_str("            (");
        aabb(out, b);
        out.push_str("),\n");
    }
    out.push_str("        ],\n        triggers: [\n");
    for (name, _, _) in &l.anchors {
        let trigger = if name.starts_with("door:") {
            door_trigger(l, name)
        } else if *name == "elevator_exit" {
            elevator_exit_trigger(l)
        } else {
            continue;
        };
        let _ = write!(out, "            ({name:?}, ");
        aabb(out, &trigger);
        out.push_str("),\n");
    }
    out.push_str("        ],\n        arrivals: [\n");
    for (name, pos, yaw) in &l.anchors {
        let Some(from) = name.strip_prefix("door:") else {
            continue;
        };
        let _ = write!(out, "            ({from:?}, ");
        bv3(out, arrival(l, *pos, *yaw));
        let _ = writeln!(out, ", {yaw:?}),");
    }
    out.push_str("        ],\n    ),\n");
}

fn render() -> String {
    let mut out = String::from(
        "// Generated by game_client floors::export (TLD_WRITE_ZONES=1 cargo test -p game_client zone_geometry).\n[\n",
    );
    // The easter-egg zone and the minigame venues have no packs or boss, so they stay out of
    // ZONE_IDS and its tests.
    for id in ZONE_IDS
        .into_iter()
        .chain([super::client::ZONE, super::teambuilding::ZONE])
        .chain(super::corporate::ZONES)
    {
        let l = build_zone(id).unwrap_or_else(|| panic!("zone {id} missing"));
        zone(&mut out, &l);
    }
    out.push_str("]\n");
    out
}

/// Numbers compare with a tolerance: libm trig may differ in the last bits across platforms.
fn same(a: &str, b: &str) -> bool {
    fn tokens(s: &str) -> Vec<&str> {
        s.split(|c: char| c.is_whitespace() || matches!(c, '(' | ')' | '[' | ']' | ','))
            .filter(|t| !t.is_empty() && !t.starts_with("//"))
            .collect()
    }
    let (ta, tb) = (tokens(a), tokens(b));
    ta.len() == tb.len()
        && ta
            .iter()
            .zip(&tb)
            .all(|(x, y)| match (x.parse::<f32>(), y.parse::<f32>()) {
                (Ok(p), Ok(q)) => (p - q).abs() <= 1e-3,
                _ => x == y,
            })
}

#[test]
fn zone_geometry_file_is_current() {
    let fresh = render();
    let on_disk = std::fs::read_to_string(PATH).unwrap_or_default();
    if std::env::var_os("TLD_WRITE_ZONES").is_some() {
        std::fs::write(PATH, &fresh).unwrap_or_else(|e| panic!("write {PATH}: {e}"));
        return;
    }
    assert!(
        same(&fresh, &on_disk),
        "content/zone_geometry.ron is stale; run TLD_WRITE_ZONES=1 cargo test -p game_client zone_geometry"
    );
}
