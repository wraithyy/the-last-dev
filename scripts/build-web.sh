#!/usr/bin/env bash
# Build game_client for wasm and generate JS glue into web/pkg. Usage: build-web.sh [--dev]
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

profile="wasm-release"
target_dir="wasm-release"
if [[ "${1:-}" == "--dev" ]]; then
  profile=dev
  target_dir=debug
fi

want=$(awk '/^name = "wasm-bindgen"$/ {getline; gsub(/[^0-9.]/, "", $0); print; exit}' Cargo.lock)
if ! command -v wasm-bindgen >/dev/null; then
  echo "error: wasm-bindgen not found. Run: cargo install wasm-bindgen-cli --version ${want} --locked" >&2
  exit 1
fi
have=$(wasm-bindgen --version | awk '{print $2}')
if [[ "$have" != "$want" ]]; then
  echo "error: wasm-bindgen ${have} != Cargo.lock ${want}. Run: cargo install wasm-bindgen-cli --version ${want} --locked --force" >&2
  exit 1
fi

cargo build -p game_client --target wasm32-unknown-unknown --profile "$profile"

wasm=target/wasm32-unknown-unknown/${target_dir}/game_client.wasm
wasm-bindgen --target web --no-typescript --out-dir web/pkg --out-name game_client "$wasm"

if command -v wasm-opt >/dev/null && [[ "$profile" != dev ]]; then
  wasm-opt -Os -o web/pkg/game_client_bg.wasm web/pkg/game_client_bg.wasm
else
  echo "wasm-opt skipped (not installed or dev build)"
fi

# Pages serves gzip, so Content-Length is the compressed size; the loader needs the real one for %.
wc -c < web/pkg/game_client_bg.wasm | tr -d ' ' > web/pkg/game_client_bg.wasm.size

if [[ -d assets ]]; then
  rm -rf web/assets
  cp -R assets web/assets
fi
# Service worker inputs: the file list to precache and a build id that changes with any of them.
# Hashing file contents (not git state) keeps local and CI builds consistent.
(
  cd web
  files=$(find index.html manifest.webmanifest icons pkg assets -type f ! -name .DS_Store | LC_ALL=C sort)
  build=$(echo "$files" | tr '\n' '\0' | xargs -0 shasum -a 256 | shasum -a 256 | cut -c1-12)
  {
    echo "// Generated by scripts/build-web.sh; do not edit."
    echo "self.BUILD = '${build}';"
    echo "self.PRECACHE = ["
    echo "$files" | sed "s/.*/  '&',/"
    echo "];"
  } > precache.js
  echo "service worker build id: ${build} ($(echo "$files" | wc -l | tr -d ' ') files)"
)
echo "ok: web/pkg ready; serve with scripts/serve-web.sh"
